import assert from 'node:assert/strict';
import { classify, reconcile } from './model.js';
import { normalizeGeometry } from './sources.js';
import { exportSvg, crownDiameter } from './svg-export.js';

const point = (id, source, x, attrs = {}) => ({ id, source, kind: 'point', category: 'Stromy', coords: [x, 2], attrs });
assert.match(classify('IPR linie', { CTMTP_KOD: 91850 }, 'line'), /^Zakryté/);
assert.match(classify('IPR body', { CTMTP_KOD: 1950 }, 'point'), /^Pomocná/);
assert.equal(classify('OSM', { highway: 'street_lamp' }, 'point'), 'Lampy');
assert.equal(classify('IPR body', { CTMTP_KOD: 76010 }, 'point'), 'Ostatní sloupy');
assert.equal(normalizeGeometry({ points: [[1, 2], [3, 4]] }, (p) => p).length, 2);
const raw = [point('a', 'IPR body', 2), point('b', 'OSM', 2.4, { diameter_crown: '6 m' })];
const result = reconcile(raw);
assert.equal(result.output.filter((f) => f.suppressed).length, 1);
assert.equal(raw[0].members, undefined);
const key = result.candidates[0].key;
assert.equal(reconcile(raw, { [key]: 'separate' }).output.filter((f) => f.suppressed).length, 0);
assert.equal(reconcile([...raw, point('c', 'OSM', 2.6)]).output.filter((f) => f.suppressed).length, 0);
assert.equal(reconcile([point('a', 'IPR body', 2, { species: 'A' }), point('b', 'OSM', 2.4, { species: 'B' })]).output.filter((f) => f.suppressed).length, 0);
assert.equal(crownDiameter(raw), 6);
assert.equal(crownDiameter([point('c', 'OSM', 2, { height: '20', diameter_crown: 'unknown' })]), null);
const svg = exportSvg({ bbox: [14, 50, 14.001, 50.001], raw, date: '2026-11-11', decisions: {}, visibility: {}, errors: [] }, result, { controls: true });
assert.ok(svg.includes('inkscape:groupmode="layer"'));
assert.ok(svg.includes('Kontrola /'));
assert.ok(svg.includes('r="3"'));
assert.ok(svg.includes('http://www.inkscape.org/namespaces/inkscape'));
console.log('Offline assertions passed');
